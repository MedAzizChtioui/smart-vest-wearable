box(84, 36, 15, 9, "Patch textile\n2,45 GHz\n(feutre, Shieldex)", "#f6dbe4")
box(84, 22, 15, 9, "Vibreur haptique\n+ LED d'alerte", "#f6dbe4")
box(30, 3, 22, 9, "PMIC nPM1300\nBuck 3,0 V + chargeur\nLiPo 200 mAh", "#fff4c2")
